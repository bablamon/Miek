function icon(name, size = 18) {
  const span = document.createElement('span');
  span.className = 'icon';
  span.innerHTML = `<svg viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] || ''}</svg>`;
  return span;
}

// Fill every [data-icon] placeholder in the static markup.
function hydrateIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    const size = el.classList.contains('playbtn') ? 20 : el.classList.contains('lg') ? 20 : 18;
    el.replaceChildren(...[icon(el.dataset.icon, size), ...[...el.childNodes].filter((n) => n.nodeType === 3 && n.textContent.trim())]);
  });
}
